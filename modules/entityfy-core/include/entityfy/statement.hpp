inline void append_joined_identifiers(std::string& output, const std::vector<column_descriptor>& columns)
{
    for(std::size_t index = 0; index < columns.size(); ++index)
    {
        if(index != 0)
        {
            output.append(", ");
        }

        output.append(quote_identifier(columns[index].name));
    }
}

inline void append_placeholders(std::string& output, std::size_t count)
{
    for(std::size_t index = 0; index < count; ++index)
    {
        if(index != 0)
        {
            output.append(", ");
        }

        output.push_back('?');
    }
}

inline void append_orderings(std::string& output, const std::vector<ordering>& orderings)
{
    if(orderings.empty())
    {
        return;
    }

    output.append(" ORDER BY ");
    for(std::size_t index = 0; index < orderings.size(); ++index)
    {
        if(index != 0)
        {
            output.append(", ");
        }

        output.append(quote_identifier(orderings[index].column));
        output.append(orderings[index].direction == sort_direction::ascending ? " ASC" : " DESC");
    }
}

inline std::string excluded_column_reference(const column_descriptor& column)
{
    return "excluded." + quote_identifier(column.name);
}

template <typename Model>
inline void append_query_tail(std::string& sql, std::vector<sql_value>& binds, query_options<Model> options, bool include_ordering = true)
{
    if(!options.filter.empty())
    {
        sql.append(" WHERE ");
        sql.append(options.filter.sql);
        std::ranges::move(options.filter.binds, std::back_inserter(binds));
    }

    if(include_ordering)
    {
        append_orderings(sql, options.orderings);
    }

    if(options.limit)
    {
        sql.append(" LIMIT ");
        sql.append(std::to_string(*options.limit));
    }

    if(options.offset)
    {
        sql.append(" OFFSET ");
        sql.append(std::to_string(*options.offset));
    }
}

inline std::string column_definition(const column_descriptor& column, dialect target, bool alter_table)
{
    std::string output = quote_identifier(column.name);
    output.push_back(' ');

    if(column.flags.primary_key && column.flags.auto_increment && target == dialect::sqlite)
    {
        output.append("INTEGER PRIMARY KEY AUTOINCREMENT");
    }
    else
    {
        output.append(column.sql_type);

        if(column.flags.primary_key && column.flags.auto_increment && target == dialect::postgresql)
        {
            output.append(" GENERATED BY DEFAULT AS IDENTITY");
        }

        if(column.flags.primary_key)
        {
            output.append(" PRIMARY KEY");
        }
    }

    if(column.flags.not_null && !column.flags.primary_key)
    {
        output.append(" NOT NULL");
    }

    if(!column.default_sql.empty())
    {
        output.append(" DEFAULT ");
        output.append(column.default_sql);
    }

    if(!column.check_sql.empty())
    {
        output.append(" CHECK (");
        output.append(column.check_sql);
        output.push_back(')');
    }

    if(column.has_reference)
    {
        output.append(" REFERENCES ");
        output.append(quote_identifier(column.reference.table));
        output.append(" (");
        output.append(quote_identifier(column.reference.column));
        output.push_back(')');

        if(!column.reference.on_delete.empty())
        {
            output.append(" ON DELETE ");
            output.append(column.reference.on_delete);
        }

        if(!column.reference.on_update.empty())
        {
            output.append(" ON UPDATE ");
            output.append(column.reference.on_update);
        }
    }

    return output;
}

