template <typename Model>
[[nodiscard]] statement create_table(const model_descriptor<Model>& model)
{
    statement output;
    output.sql = "CREATE TABLE IF NOT EXISTS ";
    output.sql.append(detail::quote_identifier(model.table_name));
    output.sql.append(" (");

    for(std::size_t index = 0; index < model.columns.size(); ++index)
    {
        if(index != 0)
        {
            output.sql.append(", ");
        }

        output.sql.append(detail::column_definition(model.columns[index], model.target, false));
    }

    output.sql.push_back(')');
    return output;
}

template <typename Model>
[[nodiscard]] statement create_table(dialect target)
{
    return create_table(describe_model<Model>(target));
}

