std::unique_ptr<provider> open_postgres_provider(std::string conninfo, const provider_options& options)
{
    if(conninfo.starts_with("postgres://"))
    {
        conninfo.replace(0, std::string{"postgres://"}.size(), "postgresql://");
    }

    return std::make_unique<postgres_provider>(std::move(conninfo), options);
}

