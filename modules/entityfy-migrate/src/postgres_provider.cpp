std::string trim_copy(std::string_view input)
{
    const auto first = input.find_first_not_of(" \t\r\n");
    if(first == std::string_view::npos)
    {
        return {};
    }

    const auto last = input.find_last_not_of(" \t\r\n");
    return std::string{input.substr(first, last - first + 1)};
}

std::string lower_copy(std::string_view input)
{
    std::string output{input};
    for(char& character: output)
    {
        character = static_cast<char>(std::tolower(static_cast<unsigned char>(character)));
    }
    return output;
}

std::string normalize_default(std::string value)
{
    value = trim_copy(value);

    if(value.empty())
    {
        return {};
    }

    if(value.front() == '\'')
    {
        std::size_t index = 1;
        for(; index < value.size(); ++index)
        {
            if(value[index] == '\'' && (index + 1 >= value.size() || value[index + 1] != '\''))
            {
                break;
            }

            if(value[index] == '\'' && index + 1 < value.size() && value[index + 1] == '\'')
            {
                ++index;
            }
        }

        return value.substr(0, std::min(index + 1, value.size()));
    }

    const auto cast = value.find("::");
    if(cast != std::string::npos)
    {
        value = trim_copy(value.substr(0, cast));
    }

    while(value.size() >= 2 && value.front() == '(' && value.back() == ')')
    {
        value = trim_copy(value.substr(1, value.size() - 2));
    }

    const std::string lowered = lower_copy(value);
    if(lowered == "now()" || lowered.starts_with("current_timestamp"))
    {
        return "CURRENT_TIMESTAMP";
    }

    if(lowered.starts_with("nextval("))
    {
        return {};
    }

    return value;
}

std::string truncate_identifier(std::string value)
{
    if(value.size() > 63)
    {
        value.resize(63);
    }

    return value;
}

std::string column_definition(const column& value, bool composite_key)
{
    std::string output = quote_ident(value.name) + " ";
    output += value.type.empty() ? "TEXT" : value.type;

    if(value.primary_key && value.auto_increment)
    {
        output += " GENERATED BY DEFAULT AS IDENTITY";
    }

    if(value.primary_key && !composite_key)
    {
        output += " PRIMARY KEY";
    }
    else if(value.not_null || (composite_key && value.primary_key))
    {
        output += " NOT NULL";
    }

    if(!value.default_sql.empty())
    {
        output += " DEFAULT " + value.default_sql;
    }

    if(!value.check_sql.empty())
    {
        output += " CHECK (" + value.check_sql + ")";
    }

    if(value.references)
    {
        output += " REFERENCES " + quote_ident(value.references->table) + " (" +
                  quote_ident(value.references->column) + ")";

        if(!value.references->on_delete.empty())
        {
            output += " ON DELETE " + value.references->on_delete;
        }

        if(!value.references->on_update.empty())
        {
            output += " ON UPDATE " + value.references->on_update;
        }
    }

    return output;
}

std::string foreign_key_name(const std::string& table, const std::vector<std::string>& columns)
{
    std::string output = "fk_" + table;
    for(const auto& column: columns)
    {
        output += "_" + column;
    }

    return truncate_identifier(std::move(output));
}

std::string foreign_key_sql(const table& value, const foreign_key& key, bool with_constraint_name)
{
    const auto columns = foreign_key_columns(key);
    const auto referenced = foreign_key_ref_columns(key);

    if(columns.empty() || columns.size() != referenced.size())
    {
        throw std::logic_error{"entityfy/migrate:postgres: foreign key on `" + value.name + "` has " +
                               std::to_string(columns.size()) + " local columns but " +
                               std::to_string(referenced.size()) + " referenced columns"};
    }

    std::string output;
    if(with_constraint_name)
    {
        output = "CONSTRAINT " + quote_ident(foreign_key_name(value.name, columns)) + " ";
    }

    output += "FOREIGN KEY (";
    for(std::size_t index = 0; index < columns.size(); ++index)
    {
        if(index != 0)
        {
            output += ", ";
        }

        output += quote_ident(columns[index]);
    }

    output += ") REFERENCES " + quote_ident(key.ref_table) + " (";
    for(std::size_t index = 0; index < referenced.size(); ++index)
    {
        if(index != 0)
        {
            output += ", ";
        }

        output += quote_ident(referenced[index]);
    }

    output += ")";

    if(!key.on_delete.empty())
    {
        output += " ON DELETE " + key.on_delete;
    }

    if(!key.on_update.empty())
    {
        output += " ON UPDATE " + key.on_update;
    }

    return output;
}

std::string create_table_sql(const table& value, bool if_not_exists)
{
    const std::vector<std::string> key_columns = primary_key_columns(value);
    const bool composite_key = key_columns.size() >= 2;

    std::string output = "CREATE TABLE ";
    if(if_not_exists)
    {
        output += "IF NOT EXISTS ";
    }

    output += quote_ident(value.name) + " (";

    for(std::size_t index = 0; index < value.columns.size(); ++index)
    {
        if(index != 0)
        {
            output += ", ";
        }

        output += column_definition(value.columns[index], composite_key);
    }

    if(composite_key)
    {
        output += ", PRIMARY KEY (";
        for(std::size_t index = 0; index < key_columns.size(); ++index)
        {
            if(index != 0)
            {
                output += ", ";
            }

            output += quote_ident(key_columns[index]);
        }

        output += ")";
    }

    for(const auto& key: value.foreign_keys)
    {
        if(foreign_key_columns(key).size() < 2)
        {
            continue;
        }

        output += ", " + foreign_key_sql(value, key, true);
    }

    output += ")";
    return output;
}

std::string create_index_sql(const table& value, const index& entry)
{
    std::string output = entry.unique ? "CREATE UNIQUE INDEX IF NOT EXISTS " : "CREATE INDEX IF NOT EXISTS ";
    output += quote_ident(entry.name) + " ON " + quote_ident(value.name) + " (";

    for(std::size_t index = 0; index < entry.columns.size(); ++index)
    {
        if(index != 0)
        {
            output += ", ";
        }

        output += quote_ident(entry.columns[index]);
    }

    output += ")";
    return output;
}

std::vector<std::string> split_columns(std::string_view value)
{
    std::vector<std::string> output;
    std::size_t start = 0;

    while(start <= value.size())
    {
        const auto comma = value.find(',', start);
        const auto end = comma == std::string_view::npos ? value.size() : comma;
        std::string column{value.substr(start, end - start)};

        if(!column.empty())
        {
            output.emplace_back(std::move(column));
        }

        if(comma == std::string_view::npos)
        {
            break;
        }

        start = comma + 1;
    }

    return output;
}

// Primary-key membership before and after a plan; PostgreSQL replaces the
// constraint instead of altering the participating columns.
struct key_change
{
    std::vector<std::string> before;
    std::vector<std::string> after;
};

struct catalog_foreign_key
{
    std::string              name;
    std::string              ref_table;
    std::vector<std::string> columns;
    std::vector<std::string> ref_columns;
};

std::vector<catalog_foreign_key> read_foreign_key_constraints(pq::database& database, const std::string& table)
{
    const auto rows = database.query_params(
        "SELECT con.conname, a.attname, rt.relname, ra.attname "
        "FROM pg_constraint con "
        "JOIN pg_class t ON t.oid = con.conrelid "
        "JOIN pg_namespace n ON n.oid = t.relnamespace "
        "JOIN pg_class rt ON rt.oid = con.confrelid "
        "JOIN LATERAL unnest(con.conkey) WITH ORDINALITY AS k(attnum, ord) ON true "
        "JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum "
        "JOIN LATERAL unnest(con.confkey) WITH ORDINALITY AS r(attnum, ord) ON r.ord = k.ord "
        "JOIN pg_attribute ra ON ra.attrelid = con.confrelid AND ra.attnum = r.attnum "
        "WHERE con.contype = 'f' AND n.nspname = current_schema() AND t.relname = $1 "
        "ORDER BY con.conname, k.ord",
        {table});

    std::vector<catalog_foreign_key> output;
    std::vector<std::pair<std::string, std::size_t>> indices;

    for(const auto& row: rows)
    {
        if(row.size() < 4)
        {
            continue;
        }

        const std::string& name = row[0];
        auto known = std::ranges::find_if(
            indices, [&](const std::pair<std::string, std::size_t>& entry) { return entry.first == name; });

        if(known == indices.end())
        {
            indices.emplace_back(name, output.size());
            output.push_back(catalog_foreign_key{.name = name, .ref_table = row[2]});
            known = indices.end() - 1;
        }

        auto& current = output[known->second];
        current.columns.push_back(row[1]);
        current.ref_columns.push_back(row[3]);
    }

    return output;
}

const std::vector<operation> empty_operations;

class postgres_provider final : public provider
{
public:
    postgres_provider(std::string conninfo, provider_options options)
        : options_{options}, database_{std::make_unique<pq::database>(std::move(conninfo))}
    {
    }

    [[nodiscard]] std::string name() const override
    {
        return "postgres";
    }

    [[nodiscard]] diff_options comparison_options() const override
    {
        return diff_options{.ignore_checks = true};
    }

    [[nodiscard]] schema introspect() override
    {
        schema output;

        const auto tables = database_->query(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' "
            "AND table_name <> 'entityfy_schema_migrations' ORDER BY table_name");

        for(const auto& table_row: tables)
        {
            if(table_row.empty())
            {
                continue;
            }

            table current;
            current.name = table_row.front();

            const auto columns = database_->query_params(
                "SELECT column_name, "
                "CASE "
                "  WHEN data_type = 'character varying' AND character_maximum_length IS NOT NULL "
                "       THEN 'VARCHAR(' || character_maximum_length::text || ')' "
                "  WHEN data_type = 'character varying' THEN 'VARCHAR' "
                "  WHEN data_type = 'numeric' AND numeric_precision IS NOT NULL "
                "       THEN 'DECIMAL(' || numeric_precision::text || ', ' || COALESCE(numeric_scale, 0)::text || ')' "
                "  WHEN data_type = 'numeric' THEN 'DECIMAL' "
                "  WHEN data_type = 'timestamp without time zone' THEN 'TIMESTAMP' "
                "  WHEN data_type = 'timestamp with time zone' THEN 'TIMESTAMP' "
                "  WHEN data_type = 'time without time zone' THEN 'TIME' "
                "  WHEN data_type = 'double precision' THEN 'DOUBLE PRECISION' "
                "  WHEN data_type = 'user-defined' THEN upper(udt_name) "
                "  ELSE upper(data_type) "
                "END, "
                "is_nullable, "
                "COALESCE(column_default, ''), "
                "COALESCE(is_identity, 'NO'), "
                "COALESCE(is_generated, 'NEVER') "
                "FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = $1 "
                "ORDER BY ordinal_position",
                {current.name});

            for(const auto& column_row: columns)
            {
                if(column_row.size() < 6 || column_row[5] == "ALWAYS")
                {
                    continue;
                }

                column entry;
                entry.name = column_row[0];
                entry.type = column_row[1];
                entry.not_null = column_row[2] == "NO";
                entry.default_sql = normalize_default(column_row[3]);
                entry.auto_increment = column_row[4] == "YES" || column_row[3].rfind("nextval(", 0) == 0;
                current.columns.emplace_back(std::move(entry));
            }

            const auto primary_keys = database_->query_params(
                "SELECT a.attname FROM pg_index i "
                "JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS k(attnum, ord) ON true "
                "JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum "
                "WHERE i.indrelid = to_regclass($1) AND i.indisprimary "
                "ORDER BY k.ord",
                {current.name});

            for(const auto& key_row: primary_keys)
            {
                if(key_row.empty())
                {
                    continue;
                }

                current.primary_key.push_back(key_row.front());

                if(column* target = find_column(current, key_row.front()))
                {
                    target->primary_key = true;
                    target->not_null = true;
                }
            }

            const auto indexes = database_->query_params(
                "SELECT i.relname, ix.indisunique, string_agg(a.attname, ',' ORDER BY s.ord) "
                "FROM pg_index ix "
                "JOIN pg_class i ON i.oid = ix.indexrelid "
                "JOIN pg_class t ON t.oid = ix.indrelid "
                "JOIN LATERAL generate_series(0, ix.indnkeyatts - 1) AS s(ord) ON true "
                "JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ix.indkey[s.ord] "
                "WHERE t.relname = $1 AND t.relnamespace = current_schema()::regnamespace "
                "AND NOT ix.indisprimary "
                "GROUP BY i.relname, ix.indisunique ORDER BY i.relname",
                {current.name});

            for(const auto& index_row: indexes)
            {
                if(index_row.size() < 3)
                {
                    continue;
                }

                index entry;
                entry.name = index_row[0];
                entry.unique = index_row[1] == "t";

                if(!index_row[2].empty())
                {
                    entry.columns = split_columns(index_row[2]);
                }

                if(!entry.columns.empty())
                {
                    current.indexes.emplace_back(std::move(entry));
                }
            }

            const auto foreign_keys = database_->query_params(
                "SELECT con.conname, a.attname, rt.relname, ra.attname, con.confupdtype, con.confdeltype "
                "FROM pg_constraint con "
                "JOIN pg_class t ON t.oid = con.conrelid "
                "JOIN pg_namespace n ON n.oid = t.relnamespace "
                "JOIN pg_class rt ON rt.oid = con.confrelid "
                "JOIN LATERAL unnest(con.conkey) WITH ORDINALITY AS k(attnum, ord) ON true "
                "JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum "
                "JOIN LATERAL unnest(con.confkey) WITH ORDINALITY AS r(attnum, ord) ON r.ord = k.ord "
                "JOIN pg_attribute ra ON ra.attrelid = con.confrelid AND ra.attnum = r.attnum "
                "WHERE con.contype = 'f' AND n.nspname = current_schema() AND t.relname = $1 "
                "ORDER BY con.conname, k.ord",
                {current.name});

            const auto action = [](const std::string& code) -> std::string {
                if(code == "c")
                {
                    return "CASCADE";
                }

                if(code == "n")
                {
                    return "SET NULL";
                }

                if(code == "d")
                {
                    return "SET DEFAULT";
                }

                if(code == "r")
                {
                    return "RESTRICT";
                }

                return {};
            };

            std::vector<std::pair<std::string, std::size_t>> key_indices;

            for(const auto& key_row: foreign_keys)
            {
                if(key_row.size() < 6)
                {
                    continue;
                }

                const std::string& name = key_row[0];
                auto known = std::ranges::find_if(
                    key_indices, [&](const std::pair<std::string, std::size_t>& entry) { return entry.first == name; });

                if(known == key_indices.end())
                {
                    key_indices.emplace_back(name, current.foreign_keys.size());

                    foreign_key entry;
                    entry.ref_table = key_row[2];
                    entry.on_update = action(key_row[4]);
                    entry.on_delete = action(key_row[5]);
                    current.foreign_keys.emplace_back(std::move(entry));
                    known = key_indices.end() - 1;
                }

                foreign_key& entry = current.foreign_keys[known->second];
                entry.columns.push_back(key_row[1]);
                entry.ref_columns.push_back(key_row[3]);
            }

            for(auto& entry: current.foreign_keys)
            {
                if(entry.columns.empty())
                {
                    continue;
                }

                entry.column = entry.columns.front();
                entry.ref_column = entry.ref_columns.front();

                if(entry.columns.size() == 1)
                {
                    if(column* target = find_column(current, entry.column))
                    {
                        target->references = reference{
                            .table = entry.ref_table,
                            .column = entry.ref_column,
                            .on_delete = entry.on_delete,
                            .on_update = entry.on_update,
                        };
                    }
                }
            }

            output.tables.emplace_back(std::move(current));
        }

        sort_schema(output);
        return output;
    }

    [[nodiscard]] plan make_plan(
        const schema& desired,
        const schema& actual,
        const diff_options& options) override
    {
        diff_options effective = options;
        effective.ignore_checks = true;

        plan output;
        const auto operations = diff_schemas(desired, actual, effective);

        // PostgreSQL cannot change primary-key membership with ALTER COLUMN, so
        // the constraint is dropped and recreated. Both sides are compared
        // directly, which also covers a change confined to table::primary_key
        // where no column operation is produced.
        std::map<std::string, key_change, std::less<>> key_changes;

        for(const auto& desired_table: desired.tables)
        {
            const table* actual_table = find_table(actual, desired_table.name);
            if(actual_table == nullptr)
            {
                continue;
            }

            std::vector<std::string> before = primary_key_columns(*actual_table);
            std::vector<std::string> after = primary_key_columns(desired_table);

            if(before != after)
            {
                key_changes.emplace(desired_table.name, key_change{std::move(before), std::move(after)});
            }
        }

        output.destructive = has_destructive(operations) || !key_changes.empty();

        if(operations.empty() && key_changes.empty())
        {
            return output;
        }

        std::vector<const table*> to_create;
        for(const auto& value: operations)
        {
            if(value.kind == op_kind::create_table)
            {
                if(const table* target = find_table(desired, value.table))
                {
                    to_create.push_back(target);
                }
            }
        }

        for(const table* target: order_for_creation(to_create))
        {
            step create;
            create.sql = create_table_sql(*target, true);
            output.steps.emplace_back(std::move(create));

            for(const auto& entry: target->indexes)
            {
                step index_step;
                index_step.sql = create_index_sql(*target, entry);
                output.steps.emplace_back(std::move(index_step));
            }
        }

        std::map<std::string, std::vector<operation>, std::less<>> by_table;
        for(const auto& value: operations)
        {
            if(value.kind == op_kind::create_table || value.kind == op_kind::drop_table)
            {
                continue;
            }

            by_table[value.table].push_back(value);
        }

        for(const auto& desired_table: desired.tables)
        {
            const auto found = by_table.find(desired_table.name);
            const auto changed_key = key_changes.find(desired_table.name);

            if(found == by_table.end() && changed_key == key_changes.end())
            {
                continue;
            }

            const table* actual_table = find_table(actual, desired_table.name);
            if(actual_table == nullptr)
            {
                continue;
            }

            // The old key goes first so the column steps run without it.
            if(changed_key != key_changes.end() && !changed_key->second.before.empty())
            {
                const auto rows = database_->query_params(
                    "SELECT c.conname FROM pg_constraint c "
                    "JOIN pg_class t ON t.oid = c.conrelid "
                    "JOIN pg_namespace n ON n.oid = t.relnamespace "
                    "WHERE c.contype = 'p' AND n.nspname = current_schema() AND t.relname = $1 LIMIT 1",
                    {desired_table.name});

                if(rows.empty() || rows.front().empty())
                {
                    throw std::runtime_error{"entityfy/migrate:postgres: primary key constraint not found for " +
                                             desired_table.name};
                }

                step drop;
                drop.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " DROP CONSTRAINT " +
                           quote_ident(rows.front().front());
                output.steps.emplace_back(std::move(drop));
            }

            const std::vector<operation>& table_operations = found == by_table.end() ? empty_operations : found->second;

            for(const auto& value: table_operations)
            {
                switch(value.kind)
                {
                case op_kind::rename_column:
                {
                    step rename;
                    rename.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " RENAME COLUMN " +
                                 quote_ident(value.old_name) + " TO " + quote_ident(value.new_name);
                    output.steps.emplace_back(std::move(rename));
                    break;
                }
                case op_kind::add_column:
                {
                    step add;
                    add.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " ADD COLUMN " +
                              column_definition(value.column_spec, false);
                    output.steps.emplace_back(std::move(add));
                    break;
                }
                case op_kind::drop_column:
                {
                    step drop;
                    drop.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " DROP COLUMN " +
                               quote_ident(value.column);
                    output.steps.emplace_back(std::move(drop));
                    break;
                }
                case op_kind::alter_column:
                {
                    const column* before = find_column(*actual_table, value.column);
                    if(before == nullptr)
                    {
                        break;
                    }

                    if(value.column_spec.auto_increment != before->auto_increment)
                    {
                        throw std::runtime_error{"entityfy/migrate:postgres: identity change requires a manual "
                                                 "migration: " +
                                                 desired_table.name + "." + value.column};
                    }

                    if(!same_type(value.column_spec.type, before->type))
                    {
                        step alter;
                        alter.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " ALTER COLUMN " +
                                    quote_ident(value.column) + " TYPE " + value.column_spec.type + " USING " +
                                    quote_ident(value.column) + "::" + value.column_spec.type;
                        output.steps.emplace_back(std::move(alter));
                    }

                    if(value.column_spec.not_null != before->not_null)
                    {
                        step alter;
                        alter.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " ALTER COLUMN " +
                                    quote_ident(value.column) +
                                    (value.column_spec.not_null ? " SET NOT NULL" : " DROP NOT NULL");
                        output.steps.emplace_back(std::move(alter));
                    }

                    if(!same_default(value.column_spec.default_sql, before->default_sql))
                    {
                        step alter;
                        alter.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " ALTER COLUMN " +
                                    quote_ident(value.column) +
                                    (value.column_spec.default_sql.empty()
                                         ? " DROP DEFAULT"
                                         : " SET DEFAULT " + value.column_spec.default_sql);
                        output.steps.emplace_back(std::move(alter));
                    }

                    if(!effective.ignore_checks &&
                       normalize_sql(value.column_spec.check_sql) != normalize_sql(before->check_sql))
                    {
                        output.warnings.push_back("check constraint changes are not migrated automatically: " +
                                                  desired_table.name + "." + value.column);
                    }
                    break;
                }
                case op_kind::add_index:
                {
                    step add;
                    add.sql = create_index_sql(desired_table, value.index_spec);
                    output.steps.emplace_back(std::move(add));
                    break;
                }
                case op_kind::drop_index:
                {
                    step drop;
                    drop.sql = "DROP INDEX IF EXISTS " + quote_ident(value.index_spec.name);
                    output.steps.emplace_back(std::move(drop));
                    break;
                }
                case op_kind::add_foreign_key:
                {
                    step add;
                    add.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " ADD " +
                              foreign_key_sql(desired_table, value.fk_spec, true);
                    output.steps.emplace_back(std::move(add));
                    break;
                }
                case op_kind::drop_foreign_key:
                {
                    const auto desired_columns = foreign_key_columns(value.fk_spec);
                    const auto desired_referenced = foreign_key_ref_columns(value.fk_spec);

                    std::string constraint;
                    for(const auto& candidate: read_foreign_key_constraints(*database_, desired_table.name))
                    {
                        if(candidate.columns == desired_columns && candidate.ref_table == value.fk_spec.ref_table &&
                           candidate.ref_columns == desired_referenced)
                        {
                            constraint = candidate.name;
                            break;
                        }
                    }

                    if(constraint.empty())
                    {
                        std::string listed;
                        for(const auto& name: desired_columns)
                        {
                            if(!listed.empty())
                            {
                                listed += ", ";
                            }

                            listed += name;
                        }

                        output.warnings.push_back("foreign key constraint not found for " + desired_table.name +
                                                  " (" + listed + ")");
                        break;
                    }

                    step drop;
                    drop.sql = "ALTER TABLE " + quote_ident(desired_table.name) + " DROP CONSTRAINT " +
                               quote_ident(constraint);
                    output.steps.emplace_back(std::move(drop));
                    break;
                }
                case op_kind::create_table:
                case op_kind::drop_table:
                    break;
                }
            }

            if(changed_key != key_changes.end() && !changed_key->second.after.empty())
            {
                std::string sql = "ALTER TABLE " + quote_ident(desired_table.name) + " ADD PRIMARY KEY (";
                const auto& after = changed_key->second.after;

                for(std::size_t index = 0; index < after.size(); ++index)
                {
                    if(index != 0)
                    {
                        sql += ", ";
                    }

                    sql += quote_ident(after[index]);
                }

                sql += ")";

                step add;
                add.sql = std::move(sql);
                output.steps.emplace_back(std::move(add));
            }
        }

        for(const auto& table_value: actual.tables)
        {
            const bool dropped = std::ranges::any_of(operations, [&](const operation& value) {
                return value.kind == op_kind::drop_table && value.table == table_value.name;
            });

            if(dropped)
            {
                step drop;
                drop.sql = "DROP TABLE IF EXISTS " + quote_ident(table_value.name) + " CASCADE";
                output.steps.emplace_back(std::move(drop));
            }
        }

        return output;
    }

    void start() override
    {
        database_->exec("BEGIN");

        try
        {
            database_->exec("SELECT pg_advisory_xact_lock(8723641)");
        }
        catch(...)
        {
            try
            {
                database_->exec("ROLLBACK");
            }
            catch(...)
            {
            }

            throw;
        }
    }

    void finish() override
    {
        database_->exec("COMMIT");
    }

    void abort() override
    {
        try
        {
            database_->exec("ROLLBACK");
        }
        catch(...)
        {
        }
    }

    void execute(const step& value) override
    {
        if(value.type == step::kind::sqlite_rebuild)
        {
            throw std::runtime_error{"entityfy/migrate:postgres: sqlite rebuild step is not valid for this provider"};
        }

        database_->exec(value.sql);
    }

    void execute_sql(std::string_view sql) override
    {
        database_->exec(sql);
    }

    void execute_params(std::string_view sql, const std::vector<std::string>& params) override
    {
        (void)database_->query_params(sql, params);
    }

    [[nodiscard]] std::vector<std::vector<std::string>> query(std::string_view sql) override
    {
        return database_->query(sql);
    }

    [[nodiscard]] std::vector<std::vector<std::string>> query_params(
        std::string_view sql,
        const std::vector<std::string>& params) override
    {
        return database_->query_params(sql, params);
    }

    void backup(std::string_view) override
    {
        // PostgreSQL DDL is transactional; rollback is done with ROLLBACK.
    }

    [[nodiscard]] std::vector<std::string> render_rebuild(const table&, const table&) override
    {
        return {};
    }

    void close() override
    {
        database_.reset();
    }

private:
    [[nodiscard]] std::vector<const table*> order_for_creation(const std::vector<const table*>& tables) const
    {
        std::vector<const table*> remaining = tables;
        std::vector<const table*> ordered;
        std::set<std::string> created;

        while(!remaining.empty())
        {
            bool progress = false;

            for(auto iterator = remaining.begin(); iterator != remaining.end();)
            {
                const table* candidate = *iterator;
                bool ready = true;

                for(const auto& key: candidate->foreign_keys)
                {
                    if(key.ref_table == candidate->name || created.contains(key.ref_table))
                    {
                        continue;
                    }

                    for(const table* other: remaining)
                    {
                        if(other->name == key.ref_table)
                        {
                            ready = false;
                            break;
                        }
                    }

                    if(!ready)
                    {
                        break;
                    }
                }

                if(ready)
                {
                    ordered.push_back(candidate);
                    created.insert(candidate->name);
                    iterator = remaining.erase(iterator);
                    progress = true;
                }
                else
                {
                    ++iterator;
                }
            }

            if(!progress)
            {
                for(const table* current: remaining)
                {
                    ordered.push_back(current);
                }
                break;
            }
        }

        return ordered;
    }

    provider_options options_;
    std::unique_ptr<pq::database> database_;
};

